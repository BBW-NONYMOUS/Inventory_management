    private void loadLog() {
        model.setRowCount(0);
        try {
            for (Object[] row : AuditDao.findAll(1000)) {
                model.addRow(row);
            }
        } catch (SQLException ex) {
            Ui.error(this, ex);
        }
        Ui.filter(sorter, searchField.getText());
    }

