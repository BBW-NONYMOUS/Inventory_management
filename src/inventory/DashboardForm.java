    private void loadData() {
        try {
            double[] valuation = ReportDao.valuation();
            totalProductsValue.setText(String.valueOf((int) valuation[0]));
            inventoryValueValue.setText(Ui.peso(valuation[2]));

            List<Product> low = ProductDao.findLowStock();
            lowStockValue.setText(String.valueOf(low.size()));
            lowStockValue.setForeground(low.isEmpty() ? Ui.GREEN : Ui.AMBER);
            for (Product p : low) {
                alertsModel.addRow(new Object[]{p.getCode(), p.getName(), p.getQuantity(), p.getReorderLevel(), p.getStatus()});
            }

            String today = LocalDate.now().toString();
            int[] movement = ReportDao.movement(today, today);
            todayMovementValue.setText(movement[0] + " / " + movement[1]);

            for (Object[] r : TransactionDao.findAll(null, 20)) {
                recentModel.addRow(new Object[]{r[0], r[1], r[2], r[3], r[8]});
            }
        } catch (SQLException ex) {
            Ui.error(this, ex);
        }
    }

