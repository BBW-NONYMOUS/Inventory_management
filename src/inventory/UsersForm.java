    private void addButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addButtonActionPerformed
        if (selected != null) {
            Ui.warn(this, "Click Clear first to enter a new account.");
            return;
        }
        String username = usernameField.getText().trim();
        String fullName = fullNameField.getText().trim();
        String password = new String(passwordField.getPassword());
        if (!username.matches("[A-Za-z0-9_.]{3,50}")) {
            Ui.warn(this, "Username must be 3-50 characters: letters, numbers, dots or underscores.");
            return;
        }
        if (fullName.isEmpty()) {
            Ui.warn(this, "Full name is required.");
            return;
        }
        if (password.length() < 6) {
            Ui.warn(this, "Password must be at least 6 characters.");
            return;
        }
        try {
            if (UserDao.usernameExists(username)) {
                Ui.warn(this, "Username " + username + " is already taken.");
                return;
            }
            UserDao.add(username, fullName, selectedRole(), selectedActive(), password);
            AuditDao.log("USER_ADD", username + " (" + roleCombo.getSelectedItem() + ")");
            loadUsers();
            clearForm();
        } catch (SQLException ex) {
            Ui.error(this, ex);
        }
    }//GEN-LAST:event_addButtonActionPerformed

    private void updateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateButtonActionPerformed
        if (selected == null) {
            Ui.warn(this, "Select an account from the list to update.");
            return;
        }
        String fullName = fullNameField.getText().trim();
        String password = new String(passwordField.getPassword());
        if (fullName.isEmpty()) {
            Ui.warn(this, "Full name is required.");
            return;
        }
        if (!password.isEmpty() && password.length() < 6) {
            Ui.warn(this, "Password must be at least 6 characters.");
            return;
        }
        boolean self = selected.getId() == Session.userId();
        if (self && (!User.ADMIN.equals(selectedRole()) || !selectedActive())) {
            Ui.warn(this, "You cannot remove admin access from, or deactivate, your own account.");
            return;
        }
        try {
            UserDao.update(selected.getId(), fullName, selectedRole(), selectedActive(), password);
            AuditDao.log("USER_UPDATE", selected.getUsername() + " (" + roleCombo.getSelectedItem() + ", "
                    + statusCombo.getSelectedItem() + (password.isEmpty() ? "" : ", password reset") + ")");
            if (self) {
                Session.setUser(new User(selected.getId(), selected.getUsername(), fullName, User.ADMIN, true, selected.getCreatedAt()));
                Nav.setupSidebar(userLabel, usersNav, auditNav);
            }
            loadUsers();
            clearForm();
        } catch (SQLException ex) {
            Ui.error(this, ex);
        }
    }//GEN-LAST:event_updateButtonActionPerformed

