    private void addButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addButtonActionPerformed
        if (selected != null) {
            Ui.warn(this, "Click Clear first to enter a new supplier.");
            return;
        }
        Supplier s = readForm();
        if (s == null) {
            return;
        }
        try {
            SupplierDao.add(s);
            AuditDao.log("SUPPLIER_ADD", s.getName());
            loadSuppliers();
            clearForm();
        } catch (SQLIntegrityConstraintViolationException ex) {
            Ui.warn(this, "A supplier with that name already exists.");
        } catch (SQLException ex) {
            Ui.error(this, ex);
        }
    }//GEN-LAST:event_addButtonActionPerformed

    private void updateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateButtonActionPerformed
        if (selected == null) {
            Ui.warn(this, "Select a supplier from the list to update.");
            return;
        }
        Supplier s = readForm();
        if (s == null) {
            return;
        }
        try {
            SupplierDao.update(s);
            AuditDao.log("SUPPLIER_UPDATE", s.getName());
            loadSuppliers();
            clearForm();
        } catch (SQLIntegrityConstraintViolationException ex) {
            Ui.warn(this, "A supplier with that name already exists.");
        } catch (SQLException ex) {
            Ui.error(this, ex);
        }
    }//GEN-LAST:event_updateButtonActionPerformed

    private void deleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteButtonActionPerformed
        if (selected == null) {
            Ui.warn(this, "Select a supplier from the list to delete.");
            return;
        }
        if (!Ui.confirm(this, "Delete supplier " + selected.getName() + "?\nProducts and past transactions will keep their records without a supplier.")) {
            return;
        }
        try {
            SupplierDao.delete(selected.getId());
            AuditDao.log("SUPPLIER_DELETE", selected.getName());
            loadSuppliers();
            clearForm();
        } catch (SQLException ex) {
            Ui.error(this, ex);
        }
    }//GEN-LAST:event_deleteButtonActionPerformed

