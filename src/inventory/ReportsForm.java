    private void setPeriod(LocalDate from, LocalDate to) {
        fromField.setText(from.toString());
        toField.setText(to.toString());
        generate();
    }

    private void generate() {
        LocalDate from;
        LocalDate to;
        try {
            from = LocalDate.parse(fromField.getText().trim());
            to = LocalDate.parse(toField.getText().trim());
        } catch (DateTimeParseException ex) {
            Ui.warn(this, "Enter dates as YYYY-MM-DD, for example " + LocalDate.now() + ".");
            return;
        }
        if (from.isAfter(to)) {
            Ui.warn(this, "The From date must be on or before the To date.");
            return;
        }
        try {
            valuation = ReportDao.valuation();
            movement = ReportDao.movement(from.toString(), to.toString());
            stockValueValue.setText(Ui.peso(valuation[2]));
            retailValueValue.setText(Ui.peso(valuation[3]));
            periodInValue.setText(String.valueOf(movement[0]));
            periodOutValue.setText(String.valueOf(movement[1]));

            dailyModel.setRowCount(0);
            for (Object[] row : ReportDao.dailySummary(from.toString(), to.toString())) {
                dailyModel.addRow(row);
            }
            categoryModel.setRowCount(0);
            for (Object[] row : ReportDao.valuationByCategory()) {
                categoryModel.addRow(row);
            }
        } catch (SQLException ex) {
            Ui.error(this, ex);
        }
    }

    private void exportCsv() {
        JFileChooser chooser = new JFileChooser();
        chooser.setSelectedFile(new File("inventory-report_" + fromField.getText().trim() + "_to_" + toField.getText().trim() + ".csv"));
        if (chooser.showSaveDialog(this) != JFileChooser.APPROVE_OPTION) {
            return;
        }
        List<String> lines = new ArrayList<>();
        lines.add("Inventory Report," + csv(fromField.getText().trim()) + " to " + csv(toField.getText().trim()));
        lines.add("Generated by," + csv(Session.getUser().getFullName()) + "," + LocalDate.now());
        lines.add("");
        lines.add("Products," + (int) valuation[0]);
        lines.add("Total Units," + (int) valuation[1]);
        lines.add(String.format(Locale.US, "Stock Value (Cost),%.2f", valuation[2]));
        lines.add(String.format(Locale.US, "Retail Value,%.2f", valuation[3]));
        lines.add("Units In (Period)," + movement[0]);
        lines.add("Units Out (Period)," + movement[1]);
        lines.add("");
        lines.add("DAILY INVENTORY SUMMARY");
        addTable(lines, dailyModel);
        lines.add("");
        lines.add("VALUATION BY CATEGORY");
        addTable(lines, categoryModel);
        try {
            Files.write(chooser.getSelectedFile().toPath(), lines, StandardCharsets.UTF_8);
            AuditDao.log("REPORT_EXPORT", chooser.getSelectedFile().getName());
            Ui.info(this, "Report saved to " + chooser.getSelectedFile().getAbsolutePath());
        } catch (IOException ex) {
            Ui.warn(this, "Could not save the file: " + ex.getMessage());
        }
    }

    private static void addTable(List<String> lines, DefaultTableModel m) {
        StringBuilder header = new StringBuilder();
        for (int c = 0; c < m.getColumnCount(); c++) {
            header.append(c > 0 ? "," : "").append(csv(m.getColumnName(c)));
        }
        lines.add(header.toString());
        for (int r = 0; r < m.getRowCount(); r++) {
            StringBuilder row = new StringBuilder();
            for (int c = 0; c < m.getColumnCount(); c++) {
                Object v = m.getValueAt(r, c);
                row.append(c > 0 ? "," : "").append(v instanceof Double ? String.format(Locale.US, "%.2f", v) : csv(String.valueOf(v)));
            }
            lines.add(row.toString());
        }
    }

    private static String csv(String s) {
        return s.contains(",") || s.contains("\"") ? "\"" + s.replace("\"", "\"\"") + "\"" : s;
    }

