    private void attemptLogin() {
        String username = usernameField.getText().trim();
        String password = new String(passwordField.getPassword());
        if (username.isEmpty() || password.isEmpty()) {
            errorLabel.setText("Please enter your username and password.");
            return;
        }
        try {
            User user = UserDao.authenticate(username, password);
            if (user == null) {
                AuditDao.logAs(null, username, "LOGIN_FAILED", "Wrong username or password");
                errorLabel.setText("Invalid username or password.");
                passwordField.setText("");
                passwordField.requestFocus();
                return;
            }
            if (!user.isActive()) {
                AuditDao.logAs(user.getId(), username, "LOGIN_FAILED", "Account is deactivated");
                errorLabel.setText("This account is deactivated. Contact the admin.");
                return;
            }
            Session.setUser(user);
            AuditDao.log("LOGIN", "Signed in as " + user.getRoleLabel());
            DashboardForm dashboard = new DashboardForm();
            dashboard.setVisible(true);
            dispose();
            Nav.showReorderAlert(dashboard);
        } catch (SQLException ex) {
            errorLabel.setText("Cannot connect to the database.");
            Ui.error(this, ex);
        }
    }

